let registered = false

/**
 * 幂等注册全部内置节点与连线类型。
 */
export function registerBuiltinNodes() {
  if (registered) return
  for (const registration of builtinNodes) {
    registerNode(registration)
  }
  registerEdge({
    type: 'default',
    label: '默认连线',
    style: { stroke: '#B8BFCD', strokeWidth: 1.5 },
    markerEnd: true,
  })
  registerEdge({
    type: 'branch',
    label: '条件分支',
    animated: true,
    style: { stroke: '#7C5CFF', strokeWidth: 2 },
    markerEnd: true,
  })
  registerEdge({
    type: 'error',
    label: '错误分支',
    animated: false,
    style: { stroke: '#D93A3F', strokeWidth: 1.5 },
    markerEnd: true,
  })
  registered = true
}

